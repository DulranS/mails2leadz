import type { useData } from "@/contexts/DataContext";
import type { BackupData } from "./backup";
import { highestInvoiceSeq } from "./invoiceNumber";

// The one place that maps everything DataContext holds onto the backup
// file. Both the Import/Export page and the expired-trial lockout screen
// call this, so a collection added to backups later can't be remembered in
// one and forgotten in the other.
export function buildBackupPayload(data: ReturnType<typeof useData>): BackupData {
  return {
    products: data.products,
    purchases: data.purchases,
    sales: data.sales,
    expenses: data.expenses,
    variableCosts: data.variableCosts,
    capitalEntries: data.capitalEntries,
    taxPayments: data.taxPayments,
    purchaseOrders: data.purchaseOrders,
    employees: data.employees,
    loans: data.loans,
    contingencies: data.contingencies,
    dataRequests: data.dataRequests,
    customers: data.customers,
    projects: data.projects,
    timeEntries: data.timeEntries,
    opportunities: data.opportunities,
    fixedAssets: data.fixedAssets,
    settings: data.settings,
    budgets: data.budgets,
    invoiceCounter: { last: highestInvoiceSeq(data.sales.map((x) => x.invoiceNo)) },
    extra: {
      receivablePayments: data.receivablePayments,
      receivableWriteOffs: data.receivableWriteOffs,
      payablePayments: data.payablePayments,
      billPayments: data.billPayments,
      saleReturns: data.saleReturns,
      supplierReturns: data.supplierReturns,
      discounts: data.discounts,
      cashCounts: data.cashCounts,
      tillPayouts: data.tillPayouts,
      stockAdjustments: data.stockAdjustments,
      stockOuts: data.stockOuts,
      playbook: data.playbook,
      leaveRecords: data.leaveRecords,
      supportCases: data.supportCases,
      feedback: data.feedbackEntries,
      tasks: data.tasks,
      bookings: data.bookings,
      events: data.events,
      cheques: data.cheques,
      mileage: data.trips,
      requests: data.requests,
      procedures: data.procedures,
      compliance: data.complianceItems,
      incidents: data.incidents,
      maintenance: data.maintenanceItems,
      kpis: data.kpis,
      reviews: data.reviews,
      risks: data.risks,
      qualityChecks: data.qualityChecks,
      businessLog: data.businessLog,
      webOrders: data.webOrders,
      priceHistory: data.priceHistory,
      accruals: data.accruals,
      candidates: data.candidates,
      obligations: data.obligations,
      improvements: data.improvements,
      supplierAlternatives: data.supplierAlternatives,
      contracts: data.contracts,
      sustainabilityEntries: data.sustainabilityEntries,
      recurringInvoiceRuns: data.recurringInvoiceRuns,
      orgLinks: Object.entries(data.orgLinks ?? {}).map(([id, link]) => ({ id, ...link })),
      memberships: data.memberships,
      farmBatches: data.farmBatches,
      tabs: data.tabs,
      shifts: data.shifts,
      shipments: data.shipments,
      rentals: data.rentals,
      consignments: data.consignments,
      businessRecords: data.businessRecords,
      workOrders: data.workOrders,
      supplierCredits: data.supplierCredits,
      customerDeposits: data.customerDeposits,
      reviewMarks: data.reviewMarks,
      suppliers: data.suppliers,
      estimates: data.estimates,
      leads: data.leads,
      recurringInvoices: data.recurringInvoices,
      recurringExpenseTemplates: data.recurringExpenseTemplates,
      recurringExpenseOccurrences: data.recurringExpenseOccurrences,
      projectCostSegments: data.projectCostSegments,
      projectMilestones: data.projectMilestones,
      bankStatementLines: data.bankStatementLines,
      journalEntries: data.journalEntries,
      auditLog: data.auditLog,
      locations: data.locations,
      stockTransfers: data.stockTransfers,
      openingBalances: data.openingBalances,
      securities: data.securities,
      investmentTxns: data.investmentTxns,
      lentLoans: data.lentLoans,
      lentLoanTxns: data.lentLoanTxns,
      collectionNotes: data.collectionNotes,
    },
  };
}
